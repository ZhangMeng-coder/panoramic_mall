package com.panoramic.trade.order.domain;

/**
 * 订单来源（商城端「从页面详情端直接点击下单还是从购物车点击结算」两条入口）。
 *
 * <p>它是<b>幂等指纹的一个敏感维度</b>（裁定 D6）：同一顾客、同一店铺、同一批 SKU，从详情页直购
 * 与从购物车结算是两次真实的、意图不同的提交，不该被指纹判成重复，故必须进指纹。</p>
 *
 * <p>⚠ 域内只区分来源、**不据此做任何行为差异**：清车由端 BFF 编排层按「`cartItemIds` 是否为空」决定，
 * 与本枚举无关。</p>
 */
public enum OrderSource {

    /** 商品详情页直接下单（不经过购物车） */
    DIRECT,

    /** 购物车结算下单（选中若干行一次提交） */
    CART
}
