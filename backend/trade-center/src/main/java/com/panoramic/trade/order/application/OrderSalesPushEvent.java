package com.panoramic.trade.order.application;

/**
 * 订单完成事件（只登记「哪一笔单要推销量」）：收货落库成功后发布，由 {@link OrderSalesPushListener}
 * 在**事务提交之后**、于线程池上执行真正的推送。
 *
 * <h3>为什么用事件而不是在收货方法里直接推</h3>
 * <ul>
 *   <li><b>时点</b>：在收货那个事务里推，会读到**未提交**的行（推送前要重新读单确认已完成），
 *       而且一次 Feign 往返被包在 DB 事务里——事务持着连接与行锁去等一个网络调用，
 *       下游慢就直接拖住收货。事件 + {@code AFTER_COMMIT} 把这两件事分开：事务只写库、提交后再说；</li>
 *   <li><b>成败</b>：推送失败**不能**回滚收货（货已收到、钱已付，为记一个销量把顾客的动作判成失败
 *       是把统计口径凌驾于业务事实之上，见 {@code SalesPort}）。落在同一个方法里时，
 *       「失败怎么办」只能靠就地 catch 表达，而 catch 在一处出现就很容易在下一次改动里被顺手去掉；
 *       分成两个方法后，回滚与不回滚是**两个类**，边界看得见。</li>
 * </ul>
 *
 * <h3>它**不保证送达**，这是刻意的</h3>
 * <p>它是进程内事件：提交之后 JVM 挂掉，这一笔推送就没了——而 {@code sales_pushed} 仍是 0，
 * 兜底扫描（{@code OrderSalesPushTask}）会重捞它。**持久性由那一列提供，不由事件提供**；
 * 故这里不需要事务性发件箱那一套（那要一张表 + 一个投递器，而同一个「重推」能力兜底扫描已经有了）。</p>
 *
 * <p>⚠ 只带单号、**不带订单聚合**：监听器要重新读一次库。多一次三查询换来的是一条重要性质——
 * 快速路径与兜底扫描**走的是同一条推送逻辑**（{@code OrderSalesPushService#pushByOrderNo}），
 * 兜底才不会漂移成「另一份实现」。⚠ 顺带这也不会有读到旧值的问题：事件在提交后才被消费。</p>
 *
 * @param orderNo 业务可读单号（已完成的那一笔）
 */
public record OrderSalesPushEvent(String orderNo) {
}
