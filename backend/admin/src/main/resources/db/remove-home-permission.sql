-- ============================================================
-- 移除 admin 权限表中的「主页」目录(id 3) / 页面(id 31)（可重复执行）
--
-- 背景：主页(/home) 已改为由 admin / 店铺端 前端各自写死置顶菜单，
--      不再作为可分配的权限项出现在「权限管理 / 分配权限」中。
-- 本脚本幂等删除：
--   1) 主页 权限在 sys_role_permission 中的授权引用；
--   2) sys_permission 中的 目录(3) 与 页面(31)。
-- 已执行或重复执行均安全（不存在则跳过）。
--
-- 注意：登录时菜单/权限由后端实时查询，前端重载即可生效，无需改 Redis 快照。
-- 执行库：panoramic_mall（可先于或同于 schema.sql 再次执行）
-- ============================================================
DELETE FROM sys_role_permission WHERE permission_id IN (3, 31);
DELETE FROM sys_permission WHERE id IN (3, 31);
