package com.panoramic.mallbff.vo;

import lombok.Data;

/**
 * 我的地址**状态**（{@code GET /addresses/status} 的出参）——下单前那条控制流的分支依据。
 *
 * <p>⚠ <b>它是派生态，不是地址数据</b>：只回答两个问题——「有没有地址」与「默认地址是哪条」，
 * 从而让页面在**不拉全量列表**的前提下走完三分支：
 * 无地址 → 去新增；有地址无默认 → 弹窗选；有默认 → 直接用默认地址下单（主路径零地址请求）。</p>
 *
 * <p>⚠ <b>本端会把它按顾客缓存</b>（键与 TTL 见 {@code docs/contracts/mall-bff.md}）：缓存里只允许放
 * 这种「控制流用的派生态」，**不放地址列表本身**——列表是给人看的数据，缓存它会让顾客看到过期的地址簿；
 * 而派生态即便陈旧也有兜底（陈旧 id 下单会被域侧 404 挡下，页面回退到重选）。</p>
 *
 * <p>⚠ <b>{@code hasAddress=false} 是合法状态、不是「读失败」</b>：新顾客确实没有地址，
 * 它照常进缓存（否则每次下单都要穿透打一次下游）。「读不到」与「没有地址」的区别在于
 * **下游读失败时本端根本不写缓存**（见 {@code AddressStatusCache}）。</p>
 */
@Data
public class AddressStatusVO {

    /**
     * 是否已有收货地址（地址簿为空即 {@code false}）
     */
    private boolean hasAddress;

    /**
     * 默认地址 id；无地址或「有地址但没设默认」时为 {@code null}
     *
     * <p>⚠ 后者是真实存在的情形：默认地址**只有两条产生路径**（首条新增自动设默认、显式设默认），
     * 故「有地址却无默认」= 删掉默认地址且还有别的地址（删除后**不自动递补**）。
     * 页面据此走「弹窗让顾客选一条」那一支。</p>
     */
    private Long defaultAddressId;
}
